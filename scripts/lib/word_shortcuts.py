"""Word's keyboard shortcut inventory, design/inventory/word/shortcuts.json (D02 T01 §17): Word's key codes, which a
capture asks Word about, and the checklist the committed file is held to.

The file joins two sources. Word's own key table (ListCommands, written by scripts/word-commands.py, source
`listcommands:<build>`) gives every key bound to a command in a document. Microsoft's published Windows list of
Word's shortcuts, read as a checklist on the date in `published:<date>` and never stored (neither its text nor its
link), gives the keys the window handles rather than a key binding: the ribbon's, a table's, Outline's, Read Mode's,
the print preview's and the task panes'. `COVERAGE` maps each of the list's tables, under our own short name, row by
row to the records that cover it; `KEY_TABLE_ONLY` names the key-table records no row of the list mentions.
"""
from shortcuts import SCOPES

# Word's key codes (the WdKey values) by the key names its own table writes, for FindKey.
KEY_CODES = {"Backspace": 8, "Tab": 9, "Return": 13, "Esc": 27, "Space": 32, "Page Up": 33, "Page Down": 34,
             "End": 35, "Home": 36, "Left": 37, "Up": 38, "Right": 39, "Down": 40, "Insert": 45, "Del": 46,
             "Clear (Num 5)": 12, "Num 0": 96, "Num 5": 101, "Num +": 107, "Num -": 109, "Num /": 111, ";": 186,
             "=": 187, "Comma": 188, "-": 189, ".": 190, "/": 191, "`": 192, "[": 219, "\\": 220, "]": 221, "'": 222,
             **{chr(c): c for c in range(ord("A"), ord("Z") + 1)}, **{str(d): 48 + d for d in range(10)},
             **{f"F{n}": 111 + n for n in range(1, 13)}}
MODIFIER_CODES = {"Ctrl": 512, "Shift": 256, "Alt": 1024}


def key_code(mods, key):
    """The code Word's FindKey takes for one chord, or None for a key Word's key bindings cannot name."""
    if key not in KEY_CODES:
        return None
    return sum(MODIFIER_CODES[m] for m in mods) | KEY_CODES[key]


