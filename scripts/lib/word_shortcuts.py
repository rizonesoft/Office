def validate(records: list) -> list:
    """What keeps the committed file from being Word's whole shortcut inventory: a record without a scope or a
    behaviour, a scope outside the set, a record the checklist does not list, an id it lists that the file lacks, and a
    table with a row no record covers or a row count other than the list's."""
    out = []
    ids = {r.get("id") for r in records if isinstance(r, dict)}
    listed = set(KEY_TABLE_ONLY)
    for name, rows in COVERAGE.items():
        if len(rows) != ROWS.get(name):
            out.append(f"the checklist's {name} table holds {len(rows)} rows, not its {ROWS.get(name)}")
        for n, row in enumerate(rows, 1):
            if not row:
                out.append(f"row {n} of the checklist's {name} table is covered by no record")
            listed.update(row)
    for rec in records:
        if not isinstance(rec, dict) or rec.get("kind") != "shortcut":
            continue
        rid = rec.get("id")
        if rec.get("scope") not in SCOPES:
            out.append(f"{rid}: no scope, or one outside the set")
        if not str(rec.get("behaviour", "")).strip():
            out.append(f"{rid}: no behaviour")
        if "condition" in rec and not str(rec["condition"]).strip():
            out.append(f"{rid}: an empty condition")
        if rid not in listed:
            out.append(f"{rid}: not on the checklist (scripts/lib/word_shortcuts.py COVERAGE or KEY_TABLE_ONLY)")
    for rid in sorted(listed - ids):
        out.append(f"{rid}: on the checklist but not in the file")
    return out
